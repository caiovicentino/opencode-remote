/** Gathers everything buildDiagnosticReport needs (all best-effort, log-only). */
function buildDiagnostics(): string {
  let logTail: string[] = [];
  try {
    logTail = readFileSync(desktopLogFile(app.getPath("userData")), "utf8")
      .split("\n")
      .filter(Boolean)
      .slice(-DIAG_LOG_TAIL);
  } catch {
    // no log file yet (fresh install) — the bundle just skips the tail
  }
  // P2-163: the daemon-sidecar.log tail rides along in the bundle — it is the
  // only daemon JSONL record in the packaged app and is redacted on disk
  // (P2-160). Missing/unreadable file → empty array → the builder renders the
  // "(sem log do sidecar)" placeholder line.
  let sidecarLogTail: string[] = [];
  try {
    sidecarLogTail = readFileSync(sidecarLogFile(app.getPath("userData")), "utf8")
      .split("\n")
      .filter(Boolean)
      .slice(-DIAG_SIDECAR_TAIL);
  } catch {
    // no sidecar log yet (fresh install) — the bundle shows the placeholder
  }
  let crashFiles: string[] = [];
  try {
    crashFiles = readdirSync(clientLogsDir(homedir()))
      .filter((f) => f.startsWith("crash-") && f.endsWith(".txt"))
      .sort()
      .slice(-10);
  } catch {
    // no crash folder yet
  }
  const { reconnecting, attempts } = reconnectState();
  return buildDiagnosticReport({
    appVersion: app.getVersion(),
    electronVersion: process.versions.electron ?? "?",
    platform: `${process.platform} ${process.arch}`,
    locale: app.getLocale(),
    packaged: app.isPackaged,
    userData: app.getPath("userData"),
    daemon: {
      healthy: trayHealthy === true,
      down: isDaemonDown(),
      reconnecting,
      attempts,
      port: activeDaemonPort(),
      portReason: daemonPortReason(),
    },
    logTail,
    sidecarLogTail,
    crashFiles,
    updateStatus: lastUpdateStatus,
    // P2-211: the state only, never the bundle path (privacy contract below).
    installLocation: bootInstallLocation?.state ?? null,
    // P2-214: the clock-skew state and the rounded offset in seconds only —
    // the machine's time itself never enters the bundle (privacy contract).
    clockSkew: lastClockSkew
      ? {
          state: lastClockSkew.state,
          skewSeconds: lastClockSkew.skewMs === null ? null : Math.round(lastClockSkew.skewMs / 1000),
        }
      : null,
    // P2-218: the login-item action and its short reason only — never a path,
    // never the decision-file location (privacy contract in this header).
    startup: bootStartup ? { state: bootStartup.action, reason: bootStartup.reason } : null,
    // P2-221: the quit-confirmation action and its short reason only — never
    // a path, never the decision-file location (privacy contract in this
    // header). null until the user asks to quit this session.
    quitConfirm: lastQuitVerdict ? { state: lastQuitVerdict.action, reason: lastQuitVerdict.reason } : null,
    // P2-223: the last frozen-window episode — duration and outcome only,
    // one line in the bundle (privacy contract in this header).
    lastHang: hangEpisode.last,
  });
}

